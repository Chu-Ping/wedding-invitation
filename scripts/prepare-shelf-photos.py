"""Generate local gallery JPEGs and their manifest; originals remain unchanged.

Optional asset preparation only: pip install Pillow pillow-heif
Run from the project root: python scripts/prepare-shelf-photos.py
"""
import json
import re
from pathlib import Path

from PIL import Image, ImageOps
from pillow_heif import register_heif_opener

register_heif_opener()
root = Path(__file__).resolve().parent.parent
source = root / 'resource/images/photos'
output = source / 'web'
output.mkdir(exist_ok=True)
sources = []
for file in source.iterdir():
    match = re.fullmatch(r'(\d+)(?:-(\d+))?\.(jpg|heic)', file.name, re.I)
    if not match or int(match[1]) < 1:
        continue
    sources.append((int(match[1]), int(match[2] or 0), file))
assert sources, 'No numbered source photos found'
sets = [[] for _ in range(max(group for group, _, _ in sources))]
names = [file.stem.lower() for _, _, file in sources]
assert len(names) == len(set(names)), 'Duplicate numbered photo filenames'
for group, _, file in sorted(sources, key=lambda entry: (entry[0], entry[1], entry[2].name)):
    with Image.open(file) as original:
        image = ImageOps.exif_transpose(original).convert('RGB')
        image.thumbnail((1600, 1600), Image.Resampling.LANCZOS)
        name = file.stem.lower() + '.jpg'
        # Do not carry location/EXIF metadata into published copies.
        image.save(output / name, quality=88, optimize=True, progressive=True)
        sets[group - 1].append({
            'src': f'resource/images/photos/web/{name}',
            'width': image.width, 'height': image.height,
        })
assert all(sets), 'Expected at least one photo in each numbered set'
current_names = {Path(photo['src']).name for group in sets for photo in group}
for generated in output.glob('*.jpg'):
    if re.fullmatch(r'\d+(?:-\d+)?\.jpg', generated.name) and generated.name not in current_names:
        generated.unlink()  # Only obsolete generated copies, never originals.
(root / 'shelf-photos.js').write_text(
    '// Generated by scripts/prepare-shelf-photos.py. Index 0 is photo set 1.\n'
    + 'export const shelfPhotoSets = ' + json.dumps(sets, indent=2) + ';\n', encoding='utf-8')
print(f'Prepared {sum(map(len, sets))} photos in {len(sets)} sets.')
