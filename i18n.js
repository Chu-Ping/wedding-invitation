const languages = ['ch', 'en', 'chs'];
const languageDetails = {
  ch: { locale: 'zh-Hant', label: '繁體中文' },
  en: { locale: 'en', label: 'English' },
  chs: { locale: 'zh-Hans', label: '简体中文' },
};
let language = 'ch';
try {
  const saved = localStorage.getItem('invitation-language');
  if (languages.includes(saved)) language = saved;
} catch {}
const bindings = new Map();
const listeners = new Set();
export function getLanguage() { return language; }
export function t(key, values = {}) {
  const template = language !== 'en' ? (language === 'chs' ? simplifiedChinese : chinese)[key] ?? key
    : key === 'Invitation：佑琦 & 竹平' ? 'Invitation: Youqi & Chu-Ping' : key;
  return template.replace(/\{(\w+)\}/g, (_, name) => t(String(values[name] ?? '')));
}
function bind(element, attribute, key, values) {
  if (!bindings.has(element)) bindings.set(element, new Map());
  bindings.get(element).set(attribute, { key, values });
  const value = t(key, values);
  if (attribute === 'textContent') element.textContent = value;
  else element.setAttribute(attribute, value);
}
export function setUIText(element, key, values = {}) { bind(element, 'textContent', key, values); }
export function setUIAttribute(element, attribute, key, values = {}) { bind(element, attribute, key, values); }
export function onLanguageChange(listener) { listeners.add(listener); }
export function setLanguage(value) {
  language = languages.includes(value) ? value : 'ch';
  try { localStorage.setItem('invitation-language', language); } catch {}
  document.documentElement.lang = languageDetails[language].locale;
  for (const [element, attributes] of bindings) {
    if (!element.isConnected) { bindings.delete(element); continue; }
    for (const [attribute, { key, values }] of attributes) bind(element, attribute, key, values);
  }
  document.querySelectorAll('[data-language-toggle]').forEach(button => {
    const next = languageDetails[languages[(languages.indexOf(language) + 1) % languages.length]];
    button.textContent = 'En - 繁 - 简';
    button.setAttribute('aria-label', `${t('Switch language')}: ${next.label}`);
  });
  listeners.forEach(listener => listener());
}
const initializedLanguageButtons = new WeakSet();
export function initLanguageControls() {
  document.querySelectorAll('[data-i18n]').forEach(element => setUIText(element, element.dataset.i18n));
  document.querySelectorAll('[data-i18n-label]').forEach(element => setUIAttribute(element, 'aria-label', element.dataset.i18nLabel));
  document.querySelectorAll('[data-language-toggle]').forEach(button => {
    if (initializedLanguageButtons.has(button)) return;
    initializedLanguageButtons.add(button);
    button.addEventListener('click', () => setLanguage(languages[(languages.indexOf(language) + 1) % languages.length]));
  });
  setLanguage(language);
}
export async function loadCopy(url) {
  const response = await fetch(url, { cache: 'no-cache' });
  if (!response.ok) throw new Error(`Text request returned ${response.status}`);
  const data = JSON.parse((await response.text()).replace(/^\uFEFF/, ''));
  if (!data || languages.some(lang => ['title', 'context'].some(field => typeof data[`${field}_${lang}`] !== 'string'))) {
    throw new Error(`Invalid multilingual text: ${url}`);
  }
  return data;
}
export function translatedCopy(data) {
  return { title: data?.[`title_${language}`]?.trim() ?? '', context: data?.[`context_${language}`]?.trim() ?? '' };
}
export function renderCopy(container, data) {
  const { title, context } = translatedCopy(data);
  container.replaceChildren();
  if (title) { const heading = document.createElement('h3'); heading.textContent = title; container.append(heading); }
  if (context) { const paragraph = document.createElement('p'); paragraph.textContent = context; container.append(paragraph); }
  return Boolean(title || context);
}
